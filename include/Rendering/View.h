#ifndef GAMEOFLIFE_VIEW_H
#define GAMEOFLIFE_VIEW_H
#include <SFML/Window/Window.hpp>

#include "Camera.h"
#include "Window.h"
#include "../../Logic/include/Factory.h"

class Model;

class View {
private:
    Window& window;
    Camera& camera;
    const Model& model;

    bool visible = true;

protected:
    [[nodiscard]] const Model& getModel() const {return model;}
    [[nodiscard]] Window& getWindow() const { return window; }
    [[nodiscard]] Camera& getCamera() const { return camera; }

public:

    //----------------------------------------------------------------------------------------------------------------------
    //Constructors & Destructor
    //----------------------------------------------------------------------------------------------------------------------
    View(Factory::Key key, const Model& model, Window& window, Camera& camera);
    virtual ~View() = default;

    //----------------------------------------------------------------------------------------------------------------------
    //Setters
    //----------------------------------------------------------------------------------------------------------------------
    void setVisible(bool visible);

    //----------------------------------------------------------------------------------------------------------------------
    //Getters
    //----------------------------------------------------------------------------------------------------------------------
    [[nodiscard]] bool isVisible() const;

    //----------------------------------------------------------------------------------------------------------------------
    //Logic
    //----------------------------------------------------------------------------------------------------------------------
    virtual void update(){}

    //----------------------------------------------------------------------------------------------------------------------
    //Subscribtions
    //----------------------------------------------------------------------------------------------------------------------

    //----------------------------------------------------------------------------------------------------------------------
    //View, Draw, Print & Debug
    //----------------------------------------------------------------------------------------------------------------------
    virtual void draw() = 0;
};
#endif //GAMEOFLIFE_VIEW_H