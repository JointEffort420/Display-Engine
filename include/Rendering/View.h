#ifndef DISPLAYENGINE_VIEW_H
#define DISPLAYENGINE_VIEW_H
#include <SFML/Window/Window.hpp>

#include "Window/Camera.h"
#include "Window/Window.h"
#include "Rendering/ViewFactory.h"

namespace eng {
    class Model;

    class View {
    private:
        Window& window;
        Camera& camera;
        const Model& model;

        bool visible = true;

    protected:
        [[nodiscard]] const Model& getModel() const {return model;}
        [[nodiscard]] Window& getWindow() const { return window; }
        [[nodiscard]] Camera& getCamera() const { return camera; }

    public:

        //----------------------------------------------------------------------------------------------------------------------
        //Constructors & Destructor
        //----------------------------------------------------------------------------------------------------------------------
        View(ViewFactory::Key key, const Model& model, Window& window, Camera& camera);
        virtual ~View() = default;

        //----------------------------------------------------------------------------------------------------------------------
        //Setters
        //----------------------------------------------------------------------------------------------------------------------
        void setVisible(bool visible);

        //----------------------------------------------------------------------------------------------------------------------
        //Getters
        //----------------------------------------------------------------------------------------------------------------------
        [[nodiscard]] bool isVisible() const;

        //----------------------------------------------------------------------------------------------------------------------
        //Logic
        //----------------------------------------------------------------------------------------------------------------------
        virtual void update(){}
        virtual void calibrate() = 0;

        //----------------------------------------------------------------------------------------------------------------------
        //Subscribtions
        //----------------------------------------------------------------------------------------------------------------------

        //----------------------------------------------------------------------------------------------------------------------
        //View, Draw, Print & Debug
        //----------------------------------------------------------------------------------------------------------------------
        virtual void draw() = 0;
    };
}

#endif//DISPLAYENGINE_VIEW_H