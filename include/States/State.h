#ifndef GAMEOFLIFE_STATE_H
#define GAMEOFLIFE_STATE_H

#include "../../Logic/include/IInputObserver.h"
#include "../../Representation/include/Camera.h"
#include "../../Logic/include/Factory.h"

class StateManager;

class State{
private:
    EngineContext& ctx;
    bool active = true;

public:
    //----------------------------------------------------------------------------------------------------------------------
    //Constructors & Destructor
    //----------------------------------------------------------------------------------------------------------------------
    State() = delete;
    explicit State(Factory::Key key, EngineContext& ctx);

    //----------------------------------------------------------------------------------------------------------------------
    //Setters
    //----------------------------------------------------------------------------------------------------------------------
    void activate();
    void deactivate();

    //----------------------------------------------------------------------------------------------------------------------
    //Getters
    //----------------------------------------------------------------------------------------------------------------------
    EngineContext& getCtx();
    [[nodiscard]] bool isActive()const;

    //----------------------------------------------------------------------------------------------------------------------
    //Logic
    //----------------------------------------------------------------------------------------------------------------------
    virtual void update() = 0;
    virtual void updateModels() = 0;
    virtual void updateViews() = 0;
    virtual void nextState(StateType stateType);

    //----------------------------------------------------------------------------------------------------------------------
    //Draw, print & debug
    //----------------------------------------------------------------------------------------------------------------------
    virtual void draw() = 0;
};

#endif //GAMEOFLIFE_STATE_H